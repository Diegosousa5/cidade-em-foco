-- Cidade em Foco
-- Estrutura inicial da tabela espacial de ocorrências.
-- Execute em um banco PostgreSQL com permissão para habilitar a extensão PostGIS.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    titulo VARCHAR(120) NOT NULL,
    descricao TEXT NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    endereco VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'aberto',
    data_criacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    localizacao GEOMETRY(POINT, 4326) NOT NULL,

    CONSTRAINT pk_ocorrencias PRIMARY KEY (id),
    CONSTRAINT ck_ocorrencias_titulo_nao_vazio
        CHECK (btrim(titulo) <> ''),
    CONSTRAINT ck_ocorrencias_descricao_nao_vazia
        CHECK (btrim(descricao) <> ''),
    CONSTRAINT ck_ocorrencias_categoria
        CHECK (btrim(categoria) <> ''),
    CONSTRAINT ck_ocorrencias_status
        CHECK (status IN ('aberto', 'em análise', 'resolvido')),
    CONSTRAINT ck_ocorrencias_endereco_nao_vazio
        CHECK (btrim(endereco) <> ''),
    CONSTRAINT ck_ocorrencias_localizacao_coordenadas
        CHECK (
            ST_X(localizacao) BETWEEN -180 AND 180
            AND ST_Y(localizacao) BETWEEN -90 AND 90
        )
);

COMMENT ON TABLE ocorrencias IS
    'Ocorrências de infraestrutura urbana com localização espacial em WGS 84 (SRID 4326).';
COMMENT ON COLUMN ocorrencias.id IS
    'Identificador único gerado pelo banco.';
COMMENT ON COLUMN ocorrencias.titulo IS
    'Título breve da ocorrência.';
COMMENT ON COLUMN ocorrencias.descricao IS
    'Descrição detalhada da ocorrência.';
COMMENT ON COLUMN ocorrencias.categoria IS
    'Categoria padrão ou categoria personalizada; não pode ser vazia e tem limite de 40 caracteres.';
COMMENT ON COLUMN ocorrencias.endereco IS
    'Endereço associado à ocorrência.';
COMMENT ON COLUMN ocorrencias.status IS
    'Status: aberto, em análise ou resolvido.';
COMMENT ON COLUMN ocorrencias.data_criacao IS
    'Data e hora de criação da ocorrência.';
COMMENT ON COLUMN ocorrencias.localizacao IS
    'Ponto espacial GEOMETRY(POINT, 4326); X é longitude e Y é latitude.';

CREATE INDEX IF NOT EXISTS idx_ocorrencias_localizacao_gist
    ON ocorrencias
    USING GIST (localizacao);
